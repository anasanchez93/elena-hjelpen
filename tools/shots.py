# Tar skjermbilder av appen (kjøres i GitHub Actions, der kartflisene kan lastes)
from playwright.sync_api import sync_playwright
U = "https://elenahjelpen.com/"
with sync_playwright() as p:
    b = p.chromium.launch()
    c = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=3, locale="nb-NO")
    pg = c.new_page()
    pg.goto(U + "#kart"); pg.wait_for_timeout(6000)
    pg.screenshot(path="tools/shots/kart.png")
    pg.fill("#mapQ", "La Loma Torrevieja"); pg.click("#mapSearch button"); pg.wait_for_timeout(4000)
    bt = pg.query_selector("#mapResults button")
    if bt: bt.click()
    pg.wait_for_timeout(5000)
    pg.evaluate("window.scrollTo(0,0)"); pg.wait_for_timeout(1500)
    pg.screenshot(path="tools/shots/kart-popup.png")
    pg.goto(U + "#kart"); pg.wait_for_timeout(4000)
    pg.fill("#mapQ", "Calle Caballero de Rodas 10, Torrevieja"); pg.click("#mapSearch button"); pg.wait_for_timeout(5000)
    bt = pg.query_selector("#mapResults button")
    if bt: bt.click()
    pg.wait_for_timeout(5000)
    pg.screenshot(path="tools/shots/kart-sok.png")
    el = pg.query_selector("#mapNear")
    if el:
        el.scroll_into_view_if_needed(); pg.wait_for_timeout(800)
        pg.screenshot(path="tools/shots/kart-naer.png")
    pg.goto(U + "#kart"); pg.wait_for_timeout(4000)
    pg.click("#mapKind button[data-k=d]"); pg.wait_for_timeout(3000)
    pg.screenshot(path="tools/shots/kart-tann.png")
    pg.goto(U + "#ordliste"); pg.wait_for_timeout(2500)
    pg.fill("#q", "dolor"); pg.wait_for_timeout(1000)
    pg.screenshot(path="tools/shots/ord.png")
    b.close()
